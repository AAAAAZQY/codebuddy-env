# -*- coding: cp936 -*-
"""把 PPT 第 10 页计划同步成纸质版定下的四条技术方向"""
import io
import sys

PAIRS = [
    ("'短期（1~3 个月）：完成【MIS-T160】激光测距与补光灯的移植接入、自检与异常上报',",
     "'短期：深入研究伺服电机控制，从电流环响应、参数自整定入手，提升低速平稳性与动态性能',"),
    ("'短期：整理所负责模块的接口文档与调试说明，降低交接成本',",
     "'短期：参与稳像功能的调参与优化，改善抖动抑制效果与异常工况稳定性',"),
    ("'中期（3~6 个月）：电机低速平稳性与电流环响应优化，降低运行噪声',",
     "'中期：学习 RTOS 的任务调度与优先级设计，尝试引入工程，改善多任务实时性与代码结构',"),
    ("'中期：推动标定流程标准化（零点 / 限位 / 方向）与关键参数版本化记录',",
     "'中期：研究模糊 PID，针对负载变化、装配差异等不确定因素做自适应补偿',"),
    ("'长期：参与控制模块平台化，沉淀测试用例与故障自检机制',",
     "'长期：沉淀调试与测试用例，参与控制模块平台化',"),
]

for p in sys.argv[1:]:
    s = io.open(p, encoding='cp936', newline='').read()
    hit = 0
    for old, new in PAIRS:
        if old in s:
            s = s.replace(old, new)
            hit += 1
        else:
            print('MISS %s : %s' % (p, old[:24]))
    io.open(p, 'w', encoding='cp936', newline='').write(s)
    print('%s  plan_replaced=%d  has_rtos=%d' % (p, hit, s.count('RTOS')))
