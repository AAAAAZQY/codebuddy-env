def patch(path):
    s = io.open(path, encoding='cp936', newline='').read()
    miss = 0
    for old, new in PAIRS:
        if old in s:
            s = s.replace(old, new)
        else:
            miss += 1
            print('MISS(%d): %s' % (miss, old[:34].replace('\n', ' ')))
    io.open(path, 'w', encoding='cp936', newline='').write(s)
    print('patched %s  miss=%d' % (path, miss))


for p in sys.argv[1:]:
    patch(p)
